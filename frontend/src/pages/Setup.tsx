export function Evidence() {
  const toast = useToast();
  return (
    <>
      <div className="page-head">
        <div>
          <h1>Evidence</h1>
          <p>Tests can't show everything. Policies, processes and decisions come from short questionnaires and the documents you upload.</p>
        </div>
        <button className="btn btn-primary" onClick={() => toast("Upload is not part of this prototype yet")}><LuUpload /> Upload document</button>
      </div>

      <section className="panel">
        <div className="panel-head"><h2>Questionnaires</h2><p>Answers are saved as you go</p></div>
        <ul className="rows">
          {[...data.questionnaires].sort((a, b) => a.due.localeCompare(b.due)).map((q) => {
            const pct = Math.round((100 * q.answered) / q.total);
            return (
              <li key={q.id}>
                <div className="row-main">
                  <b>{q.title}</b>
                  <p>{framework(q.framework).name}{q.systemId ? `, for ${system(q.systemId)!.name}` : ", whole organisation"}</p>
                  <div className="progress" style={{ marginTop: 8, maxWidth: 320 }}><span style={{ width: `${pct}%` }} /></div>
                </div>
                <div className="row-side" style={{ display: "grid", gap: 6, justifyItems: "end" }}>
                  <span>{q.answered} of {q.total} answered</span>
                  <span>Due {new Date(q.due).toLocaleDateString("en-GB", { day: "numeric", month: "short" })}</span>
                  <button className="btn btn-quiet" onClick={() => toast("Questionnaire editor comes in the next prototype round")}>Continue</button>
                </div>
              </li>
            );
          })}
        </ul>
      </section>

      <section className="panel section">
        <div className="panel-head"><h2>Documents</h2><p>Linked to the requirements they prove</p></div>
        <ul className="rows">
          {DOCUMENTS.map((d) => (
            <li key={d.name}>
              <div className="row-main"><b>{d.name}</b><p>Evidence for {d.for}</p></div>
              <div className="row-side">{d.added}</div>
            </li>
          ))}
        </ul>
      </section>
    </>
  );
}

export function RunnerSetup() {
  const toast = useToast();
  const [newKey, setNewKey] = useState<string | null>(null);
  const install = `docker run -d --name attesta-runner \\
  -e ATTESTA_API_KEY=${newKey ?? "att_live_your_key"} \\
  -e ATTESTA_REGION=eu \\
  ghcr.io/attesta/runner:0.9.2`;

  return (
    <>
      <div className="page-head">
        <div>
          <h1>Runner and API keys</h1>
          <p>The runner is a small container inside your network. It fetches the test plan, calls your model, and sends back results only.</p>
        </div>
      </div>

      <section className="panel">
        <div className="panel-head"><h2>Runners</h2></div>
        <ul className="rows">
          {data.runners.map((r) => (
            <li key={r.id}>
              <div className="row-main"><b><span className={`dot dot-${r.status}`} />{r.name}</b><p>{r.location}. Version {r.version}</p></div>
              <div className="row-side">{r.status === "busy" ? "Running a test now" : "Online"}, seen {r.lastSeen}</div>
            </li>
          ))}
        </ul>
      </section>

      <div className="grid-2 section">
        <section className="panel panel-pad">
          <h2 style={{ marginBottom: 8 }}>Install a runner</h2>
          <p className="muted small" style={{ marginBottom: 14 }}>Run this on any machine that can reach your model. It needs outbound HTTPS to our EU servers and nothing inbound.</p>
          <CodeBlock>{install}</CodeBlock>
          <p className="small muted" style={{ marginTop: 12 }}>
            The image includes AI Verify, Project Moonshot, Giskard, Syft and Trivy, with their licences in /licenses.
          </p>
        </section>

        <section className="panel">
          <div className="panel-head">
            <h2>API keys</h2>
            <button className="btn btn-quiet" onClick={() => { setNewKey("att_live_" + Math.random().toString(36).slice(2, 14)); toast("API key created"); }}>
              <LuKeyRound /> Create API key
            </button>
          </div>
          {newKey && (
            <div className="panel-pad" style={{ borderBottom: "1px solid var(--rule)", background: "var(--blue-soft)" }}>
              <b>Copy your new key now.</b> <span className="small">For security, we won't show it again.</span>
              <div style={{ marginTop: 10 }}><CodeBlock>{newKey}</CodeBlock></div>
            </div>
          )}
          <ul className="rows">
            {data.apiKeys.map((k) => (
              <li key={k.id}>
                <div className="row-main"><b>{k.label}</b><p>{k.prefix}… created {k.created}</p></div>
                <div className="row-side" style={{ display: "grid", gap: 4, justifyItems: "end" }}>
                  <span>Last used {k.lastUsed}</span>
                  <button className="btn-text" onClick={() => toast(`${k.label} key revoked`)}>Revoke</button>
                </div>
              </li>
            ))}
          </ul>
        </section>
      </div>
    </>
  );
}
